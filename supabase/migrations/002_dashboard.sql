-- Staff dashboard: order numbers, real pickup dates, status times and the
-- iPad's push notification sign-ups. Run after schema.sql. Safe to run again.

-- #1001, #1002… so staff can call out orders
alter table orders add column if not exists order_number integer generated by default as identity (start with 1001);
create unique index if not exists orders_order_number_idx on orders (order_number);

-- The actual pickup date (Pacific), instead of only "Hoy" / "Mañana"
alter table orders add column if not exists pickup_date date;
update orders
set pickup_date = (created_at at time zone 'America/Los_Angeles')::date + case when pickup_day = 'Mañana' then 1 else 0 end
where pickup_date is null;

-- When staff moved the order along, for the dashboard and later analytics
alter table orders add column if not exists accepted_at timestamptz;
alter table orders add column if not exists ready_at timestamptz;
alter table orders add column if not exists picked_up_at timestamptz;
alter table orders add column if not exists cancelled_at timestamptz;
-- For the ticket printer later
alter table orders add column if not exists printed_at timestamptz;

create index if not exists orders_pickup_date_idx on orders (pickup_date);

-- One row per device that turned on order notifications
create table if not exists push_subscriptions (
  endpoint text primary key,
  p256dh text not null,
  auth text not null,
  label text,
  created_at timestamptz not null default now()
);

alter table push_subscriptions enable row level security;
revoke all on push_subscriptions from anon, authenticated;
grant select, insert, update, delete on push_subscriptions to service_role;
